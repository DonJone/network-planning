//! 导出 Mihomo、Loon、Shadowrocket、Sing-box 四大生态规则文本

use std::fs::{self, File};
use std::io::{BufWriter, Write};
use std::path::Path;

use serde::Serialize;

use crate::Result;

pub struct Bucket {
    pub suffixes: Vec<String>,
    pub domains: Vec<String>,
    pub keywords: Vec<String>,
    pub ips: Vec<String>,
}

impl Bucket {
    fn is_empty(&self) -> bool {
        self.suffixes.is_empty() && self.domains.is_empty() && self.keywords.is_empty() && self.ips.is_empty()
    }
}

pub fn write_all(root: &Path, category: &str, bucket: &Bucket) -> Result<()> {
    let rules_dir = root.join("rules");
    write_mihomo(&rules_dir.join("mihomo"), category, bucket)?;
    write_classic(&rules_dir.join("loon"), &format!("{category}.lsr"), &format!("# Loon Remote Rule - {category}"), bucket)?;
    write_classic(
        &rules_dir.join("shadowrocket"),
        &format!("{category}.list"),
        &format!("# Shadowrocket Rule Set - {category}"),
        bucket,
    )?;
    write_singbox(&rules_dir.join("singbox"), category, bucket)
}

fn create(dir: &Path, name: &str) -> Result<BufWriter<File>> {
    fs::create_dir_all(dir)?;
    Ok(BufWriter::new(File::create(dir.join(name))?))
}

/// Mihomo YAML 规则文件 (MRS 前置源格式)：域名 (behavior: domain) 与 IP (behavior: ipcidr) 分开
fn write_mihomo(dir: &Path, category: &str, bucket: &Bucket) -> Result<()> {
    let mut file = create(dir, &format!("{category}.yaml"))?;
    writeln!(file, "# Mihomo Domain Ruleset")?;
    writeln!(file, "# Category: {category}")?;
    writeln!(file, "payload:")?;
    for suffix in &bucket.suffixes {
        writeln!(file, "  - '+.{suffix}'")?;
    }
    for domain in &bucket.domains {
        writeln!(file, "  - 'full:{domain}'")?;
    }
    for keyword in &bucket.keywords {
        writeln!(file, "  - 'keyword:{keyword}'")?;
    }
    file.flush()?;

    let mut file = create(dir, &format!("{category}_ip.yaml"))?;
    writeln!(file, "# Mihomo IPCIDR Ruleset")?;
    writeln!(file, "# Category: {category}_ip")?;
    writeln!(file, "payload:")?;
    for ip in &bucket.ips {
        writeln!(file, "  - '{ip}'")?;
    }
    file.flush()?;
    Ok(())
}

/// Loon (.lsr) 与 Shadowrocket (.list) 共用的经典规则格式
fn write_classic(dir: &Path, name: &str, header: &str, bucket: &Bucket) -> Result<()> {
    let mut file = create(dir, name)?;
    writeln!(file, "{header}")?;
    writeln!(file, "# Generated by network-planning builder")?;
    writeln!(file)?;
    for keyword in &bucket.keywords {
        writeln!(file, "DOMAIN-KEYWORD,{keyword}")?;
    }
    for suffix in &bucket.suffixes {
        writeln!(file, "DOMAIN-SUFFIX,{suffix}")?;
    }
    for domain in &bucket.domains {
        writeln!(file, "DOMAIN,{domain}")?;
    }
    for ip in &bucket.ips {
        writeln!(file, "IP-CIDR,{ip},no-resolve")?;
    }
    file.flush()?;
    Ok(())
}

#[derive(Serialize)]
struct SingboxRule<'a> {
    #[serde(skip_serializing_if = "<[String]>::is_empty")]
    domain: &'a [String],
    #[serde(skip_serializing_if = "<[String]>::is_empty")]
    domain_suffix: &'a [String],
    #[serde(skip_serializing_if = "<[String]>::is_empty")]
    domain_keyword: &'a [String],
    #[serde(skip_serializing_if = "<[String]>::is_empty")]
    ip_cidr: &'a [String],
}

#[derive(Serialize)]
struct SingboxRuleSet<'a> {
    version: u8,
    rules: Vec<SingboxRule<'a>>,
}

/// Sing-box JSON 规则源 (SRS 前置源格式)
fn write_singbox(dir: &Path, category: &str, bucket: &Bucket) -> Result<()> {
    let mut rules = Vec::new();
    if !bucket.is_empty() {
        rules.push(SingboxRule {
            domain: &bucket.domains,
            domain_suffix: &bucket.suffixes,
            domain_keyword: &bucket.keywords,
            ip_cidr: &bucket.ips,
        });
    }
    let mut file = create(dir, &format!("{category}.json"))?;
    serde_json::to_writer_pretty(&mut file, &SingboxRuleSet { version: 2, rules })?;
    file.flush()?;
    Ok(())
}
